//! ST0083 WP-04: canon's pure readers of a project's Claude Code wiring, which
//! doctor's settings and hook-script findings and `deinit` stand on.

use intentsvcs::canon::{command_paths, hook_commands, is_generated_contract, names_intent};
use std::path::{Path, PathBuf};

#[test]
fn hook_commands_reads_every_command_under_every_event_in_order() {
  let settings = serde_json::json!({
    "permissions": { "allow": ["Bash(ls)"] },
    "hooks": {
      "SessionStart": [{ "hooks": [{ "type": "command", "command": "a" }, { "type": "command", "command": "b" }] }],
      "Stop": [{ "matcher": "", "hooks": [{ "type": "command", "command": "c" }] }]
    }
  });
  assert_eq!(hook_commands(&settings), vec!["a", "b", "c"]);
  assert_eq!(hook_commands(&serde_json::json!({})), Vec::<String>::new());
}

#[test]
fn command_paths_reads_absolute_home_and_project_paths_and_nothing_else() {
  let root = Path::new("/p");
  let home = Path::new("/h");
  assert_eq!(
    command_paths(
      r#"bash "/old/machine/.claude/scripts/session-context.sh""#,
      root,
      home
    ),
    vec![PathBuf::from(
      "/old/machine/.claude/scripts/session-context.sh"
    )]
  );
  assert_eq!(
    command_paths(r#""$CLAUDE_PROJECT_DIR"/.claude/scripts/x.sh"#, root, home),
    vec![PathBuf::from("/p/.claude/scripts/x.sh")]
  );
  assert_eq!(
    command_paths("${CLAUDE_PROJECT_DIR}/hooks/y.sh; ~/bin/z", root, home),
    vec![PathBuf::from("/p/hooks/y.sh"), PathBuf::from("/h/bin/z")]
  );
  assert_eq!(
    command_paths("intent claude hook session-context", root, home),
    Vec::<PathBuf>::new()
  );
}

#[test]
fn names_intent_reads_the_header_word_and_not_a_longer_one_or_a_late_line() {
  assert!(names_intent(
    "#!/bin/bash\n#\n# session-context.sh -- Intent SessionStart hook\n"
  ));
  assert!(!names_intent(
    "#!/bin/bash\n# Intentional hook of our own\n"
  ));
  assert!(!names_intent("#!/bin/bash\n\n\n\n\n# Intent\n"));
}

#[test]
fn a_contract_is_generated_only_when_its_own_footer_names_its_template() {
  let claude = "_Generated by Intent v3 from `lib/templates/llm/_CLAUDE.md`._";
  let agents = "_Generated by Intent v3 from `lib/templates/llm/_AGENTS.md`._";
  assert!(is_generated_contract("CLAUDE.md", claude));
  assert!(is_generated_contract("AGENTS.md", agents));
  assert!(!is_generated_contract("CLAUDE.md", agents));
  assert!(!is_generated_contract("CLAUDE.md", "# our own notes\n"));
  assert!(!is_generated_contract("usage-rules.md", claude));
}
