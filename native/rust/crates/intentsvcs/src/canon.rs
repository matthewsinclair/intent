/// The chain block's markers -- the spelling v2 ACTUALLY wrote, established by
/// surveying the estate rather than by assertion.
///
/// **THE PREVIOUS VALUE WAS `# >>> intent-chain-block >>>`, UNDER A DOC COMMENT
/// CLAIMING THIS EXACT PROPERTY:** _"the same spelling v2 wrote, so a project
/// canonised by either tool is idempotent under the other."_ The requirement was
/// stated correctly and the constant contradicted it, which is worse than an
/// undocumented constant -- the comment is what a reader checks instead of the
/// estate.
///
/// **NOTHING IN THE WORLD CARRIED THE ANGLE FORM.** Across sixteen projects,
/// thirteen have a `pre-commit` and thirteen carry the colon form; the angle
/// form appeared in zero. So the presence test below never matched, every hook
/// read as unchained, and `--apply` wrote a SECOND block invoking
/// `pre-commit.intent` a second time -- then reported `0 written` on the next
/// pass, **certifying the doubled state as canonical**. A converger that
/// reaches the wrong fixed point and then agrees with itself is harder to find
/// than one that keeps drifting.
///
/// The marker names its own generator in its text, which is why the estate's
/// copies are self-identifying and the survey was decisive.
const CHAIN_START_PREFIX: &str = "# intent-chain-block:start";
const CHAIN_START: &str = "# intent-chain-block:start (generated by intent claude upgrade)";
const CHAIN_END: &str = "# intent-chain-block:end";

/// The marker v3 briefly emitted before the survey corrected it.
///
/// **RECOGNISED, NEVER WRITTEN.** A hook already carrying it has been doubled by
/// the defect above, and the repair is a human deleting one block -- not this
/// code guessing which of two live invocations to remove. Recognising it is what
/// stops a third.
const LEGACY_CHAIN_START: &str = "# >>> intent-chain-block >>>";

/// Whether this line OPENS a chain block, in either spelling.
///
/// **ANCHORED TO THE MARKER'S OWN PREFIX, NEVER TO THE SUBSTRING
/// `intent-chain-block`.** Laksa's hook carries a prose line -- _"The
/// intent-chain-block above is NOT folded in"_ -- and a `contains` predicate
/// would read that comment as a block, so a project whose block had been deleted
/// while its comment survived would silently never get one back.
fn opens_chain_block(line: &str) -> bool {
  let t = line.trim();
  t.starts_with(CHAIN_START_PREFIX) || t == LEGACY_CHAIN_START
}

/// The footer a GENERATED `CLAUDE.md` carries, naming the template it came from.
///
/// **THIS IS A CONSENT CHECK, NOT A VERSION STAMP.** A `CLAUDE.md` without it
/// was written by a person, and regenerating over it destroys work canon never
/// authored. v2 draws the same line with the same string, so a project canonised
/// by either tool reads the same to the other.
const CLAUDE_MD_MARKER: &str = "lib/templates/llm/_CLAUDE.md";

/// The footer a generated `AGENTS.md` carries, naming its template, read the
/// way [`CLAUDE_MD_MARKER`] is.
const AGENTS_MD_MARKER: &str = "lib/templates/llm/_AGENTS.md";

/// Whether `text`, the bytes of the agent contract `name`, is one Intent
/// generated: its footer names the template it came from.
///
/// **THE ONE ANSWER TO "IS THIS CONTRACT OURS"** (ST0083). Canon's consent
/// check before regenerating `CLAUDE.md`, doctor's doubled-contract finding and
/// `deinit`'s planner all ask it, so the footer is spelled once and the three
/// cannot disagree about a file.
pub fn is_generated_contract(name: &str, text: &str) -> bool {
  match name {
    "CLAUDE.md" => text.contains(CLAUDE_MD_MARKER),
    "AGENTS.md" => text.contains(AGENTS_MD_MARKER),
    _ => false,
  }
}

/// **`.claude/settings.json`'s generated marker is Intent's own hook door.**
///
/// JSON carries no comment, so there is no footer to look for the way
/// [`CLAUDE_MD_MARKER`] is looked for, and the question the marker has to answer
/// is not *are these bytes ours* but *did this file ever carry our hooks*.
///
/// **BYTE-EQUALITY WITH THE TEMPLATE WAS THE OBVIOUS ALTERNATIVE AND IT IS
/// WORSE, QUIETLY.** A project that took the door under an older template would
/// then be held for ever: a hook fix would silently never reach it, and the
/// report would say `held` while everybody assumed it had landed. Holding on
/// the door's ABSENCE holds exactly the file nobody here wrote.
const SETTINGS_MARKER: &str = "intent claude hook";

/// Whether a `.claude/settings.json`'s text carries Intent's hook door, which
/// is what makes it canon's to rewrite rather than the project's to keep.
pub fn carries_hook_door(settings: &str) -> bool {
  settings.contains(SETTINGS_MARKER)
}

/// Every hook command a Claude Code settings document wires, in document
/// order: each `.hooks.<Event>[].hooks[].command` string.
pub fn hook_commands(settings: &serde_json::Value) -> Vec<String> {
  settings
    .get("hooks")
    .and_then(serde_json::Value::as_object)
    .into_iter()
    .flat_map(|events| events.values())
    .filter_map(serde_json::Value::as_array)
    .flatten()
    .filter_map(|matcher| matcher.get("hooks")?.as_array())
    .flatten()
    .filter_map(|hook| hook.get("command")?.as_str())
    .map(str::to_string)
    .collect()
}

/// The filesystem paths a hook command names: each word that starts with `/`,
/// `~/` or `$CLAUDE_PROJECT_DIR` (bare or braced), quotes removed, with `~`
/// read as `home` and the variable as the project `root`.
///
/// **A WORD, NOT A PARSE OF THE SHELL.** The v2.12 form this exists for is one
/// absolute script path, quoted or not; a command that builds a path at run
/// time names none this can see, and is not reported.
pub fn command_paths(command: &str, root: &Path, home: &Path) -> Vec<PathBuf> {
  command
    .split_whitespace()
    .map(|word| word.replace(['"', '\''], ""))
    .map(|word| word.trim_end_matches([';', ')']).to_string())
    .filter_map(|word| {
      for var in ["${CLAUDE_PROJECT_DIR}", "$CLAUDE_PROJECT_DIR"] {
        if let Some(rest) = word.strip_prefix(var) {
          return Some(root.join(rest.trim_start_matches('/')));
        }
      }
      if let Some(rest) = word.strip_prefix("~/") {
        return Some(home.join(rest));
      }
      word.starts_with('/').then(|| PathBuf::from(&word))
    })
    .collect()
}

/// Whether a shell script's header names Intent: the word in its first five
/// lines, where every hook script v2 wrote into a project says what it is
/// (`# session-context.sh -- Intent SessionStart hook`).
pub fn names_intent(script: &str) -> bool {
  script.lines().take(5).any(|line| {
    line
      .split(|c: char| !c.is_alphanumeric())
      .any(|word| word == "Intent")
  })
}

/// The skill whose script releases the prompt gate (issue `0601`).
pub const GATE_SKILL: &str = "in-session";

/// The releaser inside an installed [`GATE_SKILL`]: what `/in-session` runs to
/// release the gate, and what the gate itself (`require-in-session.sh`) and
/// `session-context.sh` look for under `$HOME/.claude/skills/`. The install
/// step, doctor's advisory and the gate read this one path, so they cannot
/// disagree about whether the gate can be released on this machine.
pub const GATE_RELEASER: &str = "scripts/release-gate.sh";

/// Where the releaser sits under a skills directory (`~/.claude/skills/`), for
/// a caller with no [`crate::payload::Payload`] to ask, as doctor's advisory
/// has none. A test pins it equal to the payload's own layout.
pub fn releaser_under(skills_dir: &Path) -> PathBuf {
  skills_dir.join(GATE_SKILL).join(GATE_RELEASER)
}

/// What a `.claude/settings.json` that wires the prompt gate carries.
pub const GATE_HOOK: &str = "intent claude hook require-in-session";

/// What [`apply`]'s gate releaser step found or did (issue `0601`, (a1)).
///
/// **THE STEP EXISTS BECAUSE THE SETTINGS FILE WIRES A COOPERATIVE GATE.** The
/// gate blocks a session's first prompt until `/in-session` releases it, and
/// before this step nothing `upgrade --apply` did put that skill on the
/// machine, so a fresh user got a gate nothing in the session could release.
/// The gate now fails open without its releaser (0601 (b)); this step is what
/// makes the strict gate, hv's default for a fresh user, actually strict.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Releaser {
  /// The releaser was already on this machine: nothing to do.
  Present { dir: PathBuf },
  /// [`GATE_SKILL`] was installed by this run -- or, under
  /// [`Options::report`], would be.
  Installed { dir: PathBuf },
  /// [`GATE_SKILL`] is installed but carries no releaser -- an older copy or a
  /// local change. **HELD, NEVER FORCED**, as `skills sync` and `uninstall`
  /// treat a skill changed here; the gate fails open until it is brought to
  /// canon.
  Held { dir: PathBuf },
  /// The install was attempted and did not leave a releaser. Reported, never
  /// fatal: the rest of canon still applies, and the gate fails open.
  Failed { cause: String },
}

/// The markers delimiting the project's OWN directives inside a generated
/// `CLAUDE.md`.
///
/// **THE TEMPLATE PROMISES THIS IN ITS OWN TEXT AND NOTHING IMPLEMENTED IT.**
/// `lib/templates/llm/_CLAUDE.md`'s author comment reads _"Add project-specific Claude
/// directives below this line. Preserved across regeneration."_ -- a guarantee
/// written into the artefact, in the file a project's authors read, with no code
/// behind it. Measured across the estate at the cut: four projects carry content
/// between these markers (80 lines, 25, 2, 1) and every one of them would have
/// lost it to an ordinary `--apply`.
///
/// **AND `--force` WAS NOT THE GATE.** The consent check above holds back a
/// `CLAUDE.md` with no generated footer, so the belief was that only `--force`
/// could reach the block. It is the opposite: a file that DOES carry the footer
/// is regenerated on the plain path, block and all. `--force` gates
/// hand-authored files; it never gated this.
const USER_START: &str = "<!-- user:start -->";
const USER_END: &str = "<!-- user:end -->";

/// Whether a `CLAUDE.md`'s user block holds nothing a person wrote: only
/// whitespace and HTML comments between the markers, as the template seeds it,
/// or no block at all (ST0083 WP-06).
pub fn user_block_is_empty(text: &str) -> bool {
  let Some((start, end)) = user_block_span(text) else {
    return true;
  };
  let mut rest = &text[start..end];
  let mut kept = String::new();
  while let Some(open) = rest.find("<!--") {
    kept.push_str(&rest[..open]);
    rest = match rest[open..].find("-->") {
      Some(close) => &rest[open + close + 3..],
      None => "",
    };
  }
  kept.push_str(rest);
  kept.trim().is_empty()
}

/// The span strictly between the two markers, as byte offsets.
///
/// Offsets rather than lines so the carried text goes back byte for byte,
/// including its own blank lines and trailing whitespace. `None` when either
/// marker is absent -- a half-open block is not a block.
fn user_block_span(text: &str) -> Option<(usize, usize)> {
  let start = text.find(USER_START)? + USER_START.len();
  let end = text[start..].find(USER_END)? + start;
  Some((start, end))
}

/// Carry the existing file's user block into the regenerated one.
///
/// Three cases, and two of them deliberately do nothing:
///
/// - the existing file has no block -- **nothing to carry**, and inventing one
///   would put canon's placeholder into a file whose author never asked for it;
/// - the regenerated file has no block -- **nowhere to put it**, and appending
///   the content somewhere plausible is the canon-aware guessing this module
///   exists to refuse;
/// - both have one -- the existing content replaces the regenerated placeholder.
///
/// Note it runs under `--force` too. `--force` means _overwrite a hand-authored
/// file_; it has never meant _discard the project's own directives_, and reading
/// it that way is how a documented flag grows a second, undocumented effect.
pub fn carry_user_block(existing: &str, regenerated: &str) -> String {
  let (es, ee) = match user_block_span(existing) {
    Some(v) => v,
    None => return regenerated.to_string(),
  };
  let (rs, re) = match user_block_span(regenerated) {
    Some(v) => v,
    None => return regenerated.to_string(),
  };
  let mut out = String::with_capacity(regenerated.len() + (ee - es));
  out.push_str(&regenerated[..rs]);
  out.push_str(&existing[es..ee]);
  out.push_str(&regenerated[re..]);
  out
}

/// How one [`apply`] runs.
#[derive(Debug, Clone, Copy, Default)]
pub struct Options {
  /// Overwrite user-edited canon files: `CLAUDE.md` without the generated
  /// marker, `.claude/settings.json` without Intent's hook door, and
  /// `.intent_critic.yml`.
  pub force: bool,
  /// Leave the Claude Code harness wiring alone -- `.claude/settings.json`
  /// (issue `0143`) and `.mcp.json` (AC-24.1).
  ///
  /// **ONE FLAG FOR THE CLASS, BECAUSE BOTH FILES EXIST ONLY TO WIRE CLAUDE
  /// CODE.** A project that declines the lifecycle hooks and then finds an MCP
  /// server declared in its editor anyway has been told no by a flag that only
  /// half meant it. And seeded-when-absent is not a way to decline: deleting
  /// the file only means the next `--apply` seeds it again, so without this
  /// flag there is no way to say no at all.
  pub skip_settings: bool,
  /// Compute every verdict and write NOTHING -- `claude upgrade` without
  /// `--apply` (issue `0115`). The dry run used to print canon's roster, which
  /// is the same list whether every file is stale or none is; this runs the
  /// same decisions `--apply` makes, so the two modes cannot disagree about
  /// what would change. Mode repairs are not made either.
  pub report: bool,
}

/// What one `apply` did, so the caller can report rather than guess.
#[derive(Debug, Default)]
pub struct Applied {
  /// Paths whose bytes this run changed -- or, under [`Options::report`],
  /// would change.
  pub written: Vec<PathBuf>,
  /// Paths already canonical -- reported, never silent. A run that says nothing
  /// about a file it examined is indistinguishable from one that skipped it.
  pub unchanged: Vec<PathBuf>,
  /// Paths left alone because they are the project's, not canon's.
  pub preserved: Vec<PathBuf>,
  /// Paths canon COULD generate but refused to overwrite, because they carry no
  /// generated marker and `--force` was not given. Distinct from `preserved`:
  /// canon owns the template for these, and held back on consent grounds.
  pub held: Vec<PathBuf>,
  /// A `.claude/settings.json` carrying Intent's hook door that does not parse
  /// as JSON, so Intent's entries in it could not be merged (issue 0606). Held
  /// like [`Applied::held`], and named apart because its reason differs.
  pub unparseable: Vec<PathBuf>,
  /// Paths the caller told canon not to examine at all -- `.claude/settings.json`
  /// (issue `0143`) and `.mcp.json` (AC-24.1) under `--skip-settings`. Not
  /// `preserved`: nothing here was read, so nothing can be said about whose it is.
  pub skipped: Vec<PathBuf>,
  /// Hooks whose chain block this run could not bring to canon's, each with the
  /// reason (issue `0538`); their bytes were not touched. Not `held`: `--force`
  /// overwrites nothing here, because what each needs is a human's repair.
  pub blocks_held: Vec<(PathBuf, BlockHeld)>,
  /// Where the machine's gate resolved when the carrier was installed, against
  /// the install this run's templates came from; `None` when no carrier was
  /// installed at all.
  ///
  /// **A GATE THAT WAS WRITTEN IS NOT A GATE THAT CAN RUN**, and those are
  /// different claims made by the same line of output. The carrier is a shim:
  /// everything it does depends on `~/.local/share/intent/home` resolving to an install, so
  /// a run that reports `written` while that pointer is absent or dangling has
  /// installed a gate which refuses every commit -- correctly, and without
  /// anything at install time having said so. Recorded here so the caller can
  /// say it at the only moment the operator is looking.
  pub gate: Option<crate::install::GateResolution>,
  /// The prompt gate's releaser step (issue `0601`, (a1)); `None` when the
  /// step did not run: under `--skip-settings`, when the settings file that
  /// will stand does not wire the gate, or when the caller passed no skills
  /// payload (doctor's report-mode comparison does not install skills).
  pub releaser: Option<Releaser>,
}

#[derive(Debug)]
pub enum CanonError {
  Unreadable {
    path: PathBuf,
    source: std::io::Error,
  },
  Unwritable {
    path: PathBuf,
    source: std::io::Error,
  },
  RootFile(String),
  /// `agents layout` could not read or write a path it moves (ST0083). Its own
  /// variant, because the remedy names `agents layout` and not `claude upgrade`.
  LayoutIo {
    path: PathBuf,
    source: std::io::Error,
  },
  /// `agents layout` found a contract already at its destination with other
  /// bytes than the one it would move there (ST0083). Nothing was moved.
  LayoutDestinationHolds {
    path: PathBuf,
  },
  /// git refused while `agents layout` staged what it moved.
  Git(crate::gitstate::GitStateError),
  /// The `contracts` key could not be written after the contracts moved.
  Config(crate::project::ConfigWriteError),
}

impl std::fmt::Display for CanonError {
  fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
    match self {
      Self::Unreadable { path, source } => {
        write!(f, "cannot read {}: {source}", path.display())
      }
      Self::Unwritable { path, source } => {
        write!(f, "cannot write {}: {source}", path.display())
      }
      Self::RootFile(msg) => write!(f, "{msg}"),
      Self::LayoutIo { path, source } => write!(
        f,
        "cannot move the contracts at {}: {source}",
        path.display()
      ),
      Self::LayoutDestinationHolds { path } => write!(
        f,
        "{} already holds a different file, so the contracts were not moved",
        path.display()
      ),
      Self::Git(source) => write!(f, "git refused while staging the moved contracts: {source}"),
      Self::Config(source) => write!(
        f,
        "the contracts moved and the key was not written: {source}"
      ),
    }
  }
}

/// The hooks that bring the store up to a pull, a branch checkout or a rewrite
/// (ST0078 WP-03). Each gets a chain block exactly as `pre-commit` does, and a
/// `<hook>.intent` carrier written from the one template `hooks/post-pull.sh`.
pub const POST_PULL_HOOKS: [&str; 3] = ["post-merge", "post-checkout", "post-rewrite"];

/// The chain block for `hook`, verbatim. Emitted rather than templated because
/// a template file would put its only copy behind a path lookup that can fail
/// at exactly the moment the hook matters.
///
/// **ONE BLOCK FOR EVERY HOOK, NAMED BY THE HOOK IT SITS IN.** Each calls its
/// own `<hook>.intent` carrier with git's arguments. A post-pull carrier always
/// exits 0, so the `|| exit $?` that makes the pre-commit gate refuse costs
/// those hooks nothing.
///
/// **AND IT SAYS SO WHEN THERE IS NO CARRIER TO CALL** (issue `0538`). The
/// block had no `else`, so an absent carrier, one git cannot execute, or a
/// failed `git rev-parse` skipped the gate and printed nothing: the silent pass
/// [`install_carrier`] exists to end, still reachable, because the carrier is
/// gitignored and a clone or worktree reached through `core.hooksPath` gets the
/// hook without it. The gate now REFUSES there, as the shim does (hv ruling 4).
/// The hooks path is read with `|| :` so that a failed `git rev-parse` falls
/// through to that refusal: in a hook under `set -e`, as Intent's own are, the
/// bare assignment aborted the hook first, at rc 128 with nothing printed.
///
/// **A POST-PULL HOOK WARNS AND EXITS 0.** It runs after git has changed the
/// tree, so there is nothing left to refuse, and a `post-checkout` that exits
/// non-zero becomes the exit code of `git checkout`, `git switch` and `git
/// worktree add` (measured on git 2.55.0, 2026-09-23). Refusing would report as
/// failed a checkout that happened, in every fresh worktree of such an estate.
///
/// **AND IT WARNS ONLY WHERE THERE IS A STORE TO BE BEHIND** (vc's ruling,
/// 2026-09-23): `intent/.cache/intent.db` under the checkout's top level. With
/// no store there is nothing to bring up to date, and the first `intent`
/// command there builds one, so silence loses nothing. That is every judging
/// worktree a node makes, and two lines on each `git worktree add` in them
/// would teach a reader to skip the warning. The path is the default
/// `intent_dir`'s, which every estate on this machine uses (18 configs read,
/// 2026-09-23); a project that moves `intent_dir` gets the silence.
fn chain_block(hook: &str) -> String {
  let say = |text: &str| format!("  echo \"{hook}: {text}\" >&2");
  let otherwise = if POST_PULL_HOOKS.contains(&hook) {
    vec![
      "elif [ -f \"$(git rev-parse --show-toplevel 2>/dev/null || :)/intent/.cache/intent.db\" ]; then"
        .to_string(),
      say("Intent's store was NOT brought up to date: no executable carrier at $_intent_chain"),
      say("  remedy: intent claude upgrade --apply, then intent sync --apply"),
    ]
  } else {
    vec![
      "elif [ -e \"$_intent_chain\" ]; then".to_string(),
      say("GATE NOT EXECUTABLE -- the Intent gate did NOT run: no guard, no critic, no doctor."),
      say("  the carrier has no execute bit: $_intent_chain"),
      say("  remedy: intent claude upgrade --apply"),
      "  exit 1".to_string(),
      "else".to_string(),
      say("GATE ABSENT -- the Intent gate did NOT run: no guard, no critic, no doctor."),
      say("  this hook declares a gate it cannot find: $_intent_chain"),
      say("  the carrier is gitignored, so no clone or worktree receives it."),
      say("  remedy: intent claude upgrade --apply"),
      "  exit 1".to_string(),
    ]
  };
  let mut lines = vec![
    CHAIN_START.to_string(),
    format!("_intent_chain=\"$(git rev-parse --git-path hooks 2>/dev/null || :)/{hook}.intent\""),
    "if [ -x \"$_intent_chain\" ]; then".to_string(),
    "  \"$_intent_chain\" \"$@\" || exit $?".to_string(),
  ];
  lines.extend(otherwise);
  lines.push("fi".to_string());
  lines.push(CHAIN_END.to_string());
  lines.join("\n") + "\n"
}

/// The lines of a pre-commit hook that lie OUTSIDE its chain block, each with
/// its 1-based line number.
///
/// **THE MARKERS HAVE ONE HOME AND IT IS HERE**, so `doctor` asks this rather
/// than spelling `# intent-chain-block:end` a second time. A block opened and
/// never closed runs to the end of the file: everything after an unclosed
/// opener is the block's, never the project's.
pub fn lines_outside_chain_block(text: &str) -> Vec<(usize, &str)> {
  let mut inside = false;
  let mut out = Vec::new();
  for (i, line) in text.lines().enumerate() {
    if inside {
      if line.trim() == CHAIN_END {
        inside = false;
      }
      continue;
    }
    if opens_chain_block(line) {
      inside = true;
      continue;
    }
    out.push((i + 1, line));
  }
  out
}

/// `settings` without what Intent adds to it: the hook entries whose command
/// carries Intent's hook door, and the deny rules `template` carries, emptied
/// containers dropped (ST0083 WP-06, issue 0606).
///
/// **ONE SURGERY FOR BOTH DIRECTIONS.** `intent deinit` writes what this
/// returns, and [`merge_settings`] puts the template's entries back on it, so
/// what Intent removes and what it re-adds are the same entries by
/// construction.
pub fn strip_settings(settings: &Value, template: &Value) -> Value {
  let deny = template
    .pointer("/permissions/deny")
    .and_then(Value::as_array)
    .cloned()
    .unwrap_or_default();
  let mut out = settings.clone();
  if let Some(events) = out.get_mut("hooks").and_then(Value::as_object_mut) {
    for matchers in events.values_mut() {
      if let Some(matchers) = matchers.as_array_mut() {
        for matcher in matchers.iter_mut() {
          if let Some(hooks) = matcher.get_mut("hooks").and_then(Value::as_array_mut) {
            hooks.retain(|hook| {
              !hook
                .get("command")
                .and_then(Value::as_str)
                .is_some_and(carries_hook_door)
            });
          }
        }
        matchers.retain(|matcher| {
          !matcher
            .get("hooks")
            .and_then(Value::as_array)
            .is_some_and(Vec::is_empty)
        });
      }
    }
    events.retain(|_, matchers| !matchers.as_array().is_some_and(Vec::is_empty));
  }
  if let Some(rules) = out
    .pointer_mut("/permissions/deny")
    .and_then(Value::as_array_mut)
  {
    rules.retain(|rule| !deny.contains(rule));
  }
  if let Some(permissions) = out.get_mut("permissions").and_then(Value::as_object_mut) {
    permissions.retain(|_, v| !v.as_array().is_some_and(Vec::is_empty));
  }
  drop_empty(&mut out, &["hooks", "permissions"]);
  out
}

/// Remove each of `keys` from `doc` whose value is an empty object.
pub(crate) fn drop_empty(doc: &mut Value, keys: &[&str]) {
  if let Some(map) = doc.as_object_mut() {
    for key in keys {
      if map
        .get(*key)
        .and_then(Value::as_object)
        .is_some_and(serde_json::Map::is_empty)
      {
        map.remove(*key);
      }
    }
  }
}

/// Two-space JSON with a trailing newline, as Intent writes its own.
pub fn render_json(doc: &Value) -> String {
  // A `Value` parsed from text has no failing case in serde_json's serialiser.
  #[allow(
    clippy::expect_used,
    reason = "INVARIANT: a Value parsed from JSON text has no failing case in serde_json's serialiser"
  )]
  let text = serde_json::to_string_pretty(doc).expect("a parsed Value serialises");
  text + "\n"
}

/// A marker-carrying `.claude/settings.json` brought to canon (issue 0606):
/// Intent's entries stripped by [`strip_settings`], the template's hook
/// entries and deny rules put back, and every key of the owner's kept.
///
/// **IDEMPOTENT BY CONSTRUCTION**: Intent's matchers are appended after the
/// owner's within each event, so a second run strips and appends the same
/// entries and returns the document unchanged.
pub fn merge_settings(existing: &Value, template: &Value) -> Value {
  let mut out = strip_settings(existing, template);
  let (Some(map), Some(wanted)) = (out.as_object_mut(), template.as_object()) else {
    return template.clone();
  };
  for (key, value) in wanted {
    match (key.as_str(), value.as_object()) {
      ("hooks", Some(events)) => {
        let slot = map
          .entry("hooks")
          .or_insert_with(|| Value::Object(serde_json::Map::new()));
        if let Some(slot) = slot.as_object_mut() {
          for (event, matchers) in events {
            let list = slot
              .entry(event.clone())
              .or_insert_with(|| Value::Array(Vec::new()));
            if let (Some(list), Some(matchers)) = (list.as_array_mut(), matchers.as_array()) {
              list.extend(matchers.iter().cloned());
            }
          }
        }
      }
      ("permissions", Some(rules)) => {
        let slot = map
          .entry("permissions")
          .or_insert_with(|| Value::Object(serde_json::Map::new()));
        if let Some(slot) = slot.as_object_mut() {
          for (kind, entries) in rules {
            let list = slot
              .entry(kind.clone())
              .or_insert_with(|| Value::Array(Vec::new()));
            if let (Some(list), Some(entries)) = (list.as_array_mut(), entries.as_array()) {
              for entry in entries {
                if !list.contains(entry) {
                  list.push(entry.clone());
                }
              }
            }
          }
        }
      }
      _ => {
        map.entry(key.clone()).or_insert_with(|| value.clone());
      }
    }
  }
  out
}

/// What `claude upgrade --apply` writes to a `.claude/settings.json` that
/// carries Intent's hook door (issue 0606): the template's own bytes when the
/// merge comes to the template, the file's own bytes when it changes nothing,
/// and the merge as 2-space JSON otherwise. `None` when the file does not
/// parse, so the caller holds it as it holds a file that is not Intent's.
fn settings_merged(current: &str, template_text: &str) -> Option<String> {
  let existing: Value = serde_json::from_str(current).ok()?;
  let Ok(template) = serde_json::from_str::<Value>(template_text) else {
    return Some(template_text.to_string());
  };
  let merged = merge_settings(&existing, &template);
  Some(if merged == template {
    template_text.to_string()
  } else if merged == existing {
    current.to_string()
  } else {
    render_json(&merged)
  })
}

/// Whether a trimmed hook line is preamble: the shebang, a blank line, or shell
/// discipline (`set -e`). The chain block goes after it, and a hook that is
/// nothing else once its block is cut carries nothing of the project's.
fn is_preamble(trimmed: &str) -> bool {
  trimmed.starts_with("#!")
    || trimmed.is_empty()
    || trimmed.starts_with("set -")
    || trimmed.starts_with("set +")
}

/// Every git hook canon puts a chain block in: the gate and the post-pull
/// hooks, in the order [`apply`] wires them.
pub fn chained_hooks() -> [&'static str; 4] {
  let [a, b, c] = POST_PULL_HOOKS;
  ["pre-commit", a, b, c]
}

