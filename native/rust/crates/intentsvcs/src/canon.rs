pub fn carrier_name(hook: &str) -> String {
  format!("{hook}.intent")
}

/// The template a hook's carrier is written from.
pub fn carrier_artefact(hook: &str) -> Artefact {
  if hook == "pre-commit" {
    Artefact::PreCommitCarrier
  } else {
    Artefact::PostPullCarrier
  }
}

/// `existing` with its one chain block cut out, markers included, and every
/// other byte kept; `None` when there is no block, or when
/// [`chain_block_held`] says the block is not one to touch (ST0083 WP-06).
pub fn cut_chain_block(existing: &str) -> Option<String> {
  if chain_block_held(existing).is_some() {
    return None;
  }
  let lines: Vec<&str> = existing.split_inclusive('\n').collect();
  let start = lines.iter().position(|line| opens_chain_block(line))?;
  let end = (start..lines.len()).find(|&i| lines[i].trim() == CHAIN_END)?;
  // **THE ONE BLANK LINE [`insert_chain_block`] PUTS AFTER THE BLOCK GOES WITH
  // IT**, so a cut hook reads as it did before canon wired it.
  let after = match lines.get(end + 1) {
    Some(line) if line.trim().is_empty() => end + 2,
    _ => end + 1,
  };
  Some(lines[..start].concat() + &lines[after..].concat())
}

/// Whether a hook's text is preamble alone, so nothing in it is the project's.
pub fn is_only_preamble(text: &str) -> bool {
  text.lines().all(|line| is_preamble(line.trim()))
}

/// Insert `hook`'s chain block into that hook's existing text, or bring a block
/// already there to canon's form.
///
/// **RETURNS `None` WHEN CANON'S BLOCK IS ALREADY THERE**, so the caller writes
/// nothing and the file's mtime does not move. Idempotence is a property of
/// this function rather than of the caller remembering to check.
///
/// Everything not the block is passed through byte for byte. See the module
/// header for why that is a requirement and not a convenience.
pub fn insert_chain_block(hook: &str, existing: &str) -> Option<String> {
  if existing.lines().any(opens_chain_block) {
    return rewrite_chain_block(existing, &chain_block(hook));
  }

  // An empty or absent hook gets a shebang and the block, which is the whole
  // file. Handled first because the preamble walk below has nothing to walk.
  if existing.trim().is_empty() {
    return Some(format!("#!/usr/bin/env bash\n\n{}", chain_block(hook)));
  }

  let mut out = String::new();
  let mut inserted = false;
  for line in existing.lines() {
    if !inserted {
      let t = line.trim();
      // The preamble is the shebang, blank lines, and shell discipline. The
      // block goes after it so it runs as the first REAL command, under the
      // same `set -e` the rest of the hook was written against.
      //
      // **COMMENTS ARE NOT PREAMBLE, DELIBERATELY.** v2 skipped them too, and a
      // hook whose header comment explains what the hook does would otherwise
      // get the block wedged between the explanation and the code it explains.
      if is_preamble(t) {
        out.push_str(line);
        out.push('\n');
        continue;
      }
      out.push_str(&chain_block(hook));
      out.push('\n');
      inserted = true;
    }
    out.push_str(line);
    out.push('\n');
  }

  // A file that is nothing but preamble never hit the insertion point.
  if !inserted {
    out.push('\n');
    out.push_str(&chain_block(hook));
  }
  Some(out)
}

/// Bring the one chain block in `existing` to `block`, in place (issue
/// `0538`): the lines from its opener to its end marker are replaced, and
/// every other byte is kept, its line endings included.
///
/// **`None` WHEN THE BLOCK IS ALREADY `block`, AND WHEN [`chain_block_held`]
/// SAYS IT CANNOT BE REWRITTEN SAFELY.** The caller tells the two apart by
/// asking that function, which is the one place the decision is made.
fn rewrite_chain_block(existing: &str, block: &str) -> Option<String> {
  if chain_block_held(existing).is_some() {
    return None;
  }
  let lines: Vec<&str> = existing.split_inclusive('\n').collect();
  let start = lines.iter().position(|line| opens_chain_block(line))?;
  let end = (start..lines.len()).find(|&i| lines[i].trim() == CHAIN_END)?;
  if lines[start..=end].concat() == block {
    return None;
  }
  let mut out = lines[..start].concat();
  out.push_str(block);
  out.push_str(&lines[end + 1..].concat());
  Some(out)
}

/// Why the chain block already in a hook cannot be rewritten in place (issue
/// `0538`). The hook is left exactly as it is, so the block in it may still be
/// one that passes a commit it cannot gate; `claude upgrade` names the hook and
/// the reason, because this is the one case that keeps an old block.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BlockHeld {
  /// Two openers: the hook was doubled, and deleting one of two live
  /// invocations is a human's call.
  Doubled,
  /// The retired `# >>> intent-chain-block >>>` marker, which only that
  /// doubling ever left behind.
  RetiredMarker,
  /// An opener with no end marker, so there is no bound to rewrite within.
  Unclosed,
}

impl std::fmt::Display for BlockHeld {
  fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
    f.write_str(match self {
      Self::Doubled => "it carries two chain blocks, and one is a human's to delete",
      Self::RetiredMarker => {
        "it carries the retired `# >>> intent-chain-block >>>` marker, left by a doubling a human has to repair"
      }
      Self::Unclosed => "its chain block has no `# intent-chain-block:end`, so there is no bound to rewrite within",
    })
  }
}

/// Whether the chain block in `existing` is one this code must leave alone,
/// and why. `None` for a hook with no block, or with one block it can rewrite.
pub fn chain_block_held(existing: &str) -> Option<BlockHeld> {
  let openers: Vec<&str> = existing.lines().filter(|l| opens_chain_block(l)).collect();
  if openers.iter().any(|l| l.trim() == LEGACY_CHAIN_START) {
    return Some(BlockHeld::RetiredMarker);
  }
  if openers.len() > 1 {
    return Some(BlockHeld::Doubled);
  }
  let mut after_opener = existing.lines().skip_while(|l| !opens_chain_block(l));
  let opened = after_opener.next().is_some();
  let closed = after_opener.any(|l| l.trim() == CHAIN_END);
  (opened && !closed).then_some(BlockHeld::Unclosed)
}

/// Read a canon template out of the install home.
fn template(install: &Path, rel: &str) -> Result<String, CanonError> {
  let path = install.join("lib/templates").join(rel);
  std::fs::read_to_string(&path).map_err(|source| CanonError::Unreadable { path, source })
}

/// Write `content` to `path`, creating parents, unless the bytes already match.
///
/// **THE NO-CHANGE CASE DOES NOT WRITE.** A root file whose bytes did not
/// change must not move its mtime and wake every watcher in the tree -- the
/// same reason [`crate::rootfiles::sync`] goes through a `WriteSet`.
fn write_if_changed(
  path: &Path,
  content: &str,
  report: bool,
  applied: &mut Applied,
) -> Result<(), CanonError> {
  if let Ok(current) = std::fs::read_to_string(path)
    && current == content
  {
    applied.unchanged.push(path.to_path_buf());
    return Ok(());
  }
  if report {
    applied.written.push(path.to_path_buf());
    return Ok(());
  }
  if let Some(parent) = path.parent() {
    std::fs::create_dir_all(parent).map_err(|source| CanonError::Unwritable {
      path: parent.to_path_buf(),
      source,
    })?;
  }
  std::fs::write(path, content).map_err(|source| CanonError::Unwritable {
    path: path.to_path_buf(),
    source,
  })?;
  applied.written.push(path.to_path_buf());
  Ok(())
}

/// A template to seed and what renders it: the install it is read from, its
/// path there, and the project's config and render context for its tokens.
/// The files canon lays down from a template, each naming its template once.
///
/// **THE ONE HOME OF EACH TEMPLATE'S PATH** (ST0083 WP-06): canon writes from
/// it and `deinit` compares against it, so the two cannot come to disagree
/// about which bytes are Intent's.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Artefact {
  /// `.claude/settings.json`, written whole.
  Settings,
  /// `.mcp.json`, seeded when absent.
  Mcp,
  /// `usage-rules.md`, seeded when absent.
  UsageRules,
  /// `.intent_critic.yml`, seeded when absent.
  CriticConfig,
  /// `<hooks>/pre-commit.intent`, the gate's carrier.
  PreCommitCarrier,
  /// `<hooks>/<hook>.intent` for each post-pull hook.
  PostPullCarrier,
}

impl Artefact {
  /// The template's path under the install's `lib/templates/`.
  fn rel(self) -> &'static str {
    match self {
      Self::Settings => ".claude/settings.json",
      Self::Mcp => "_mcp.json",
      Self::UsageRules => "llm/_usage-rules.md",
      Self::CriticConfig => "_intent_critic.yml",
      Self::PreCommitCarrier => "hooks/pre-commit-shim.sh",
      Self::PostPullCarrier => "hooks/post-pull.sh",
    }
  }
}

/// The bytes canon writes for `artefact` in this project: a seed rendered
/// through `seed_body`, anything else the template as it stands.
pub fn canon_bytes(
  artefact: Artefact,
  home: &Path,
  cfg: &Config,
  ctx: &RenderContext<'_>,
) -> Result<String, CanonError> {
  match artefact {
    Artefact::Mcp | Artefact::UsageRules | Artefact::CriticConfig => seed_body(&Template {
      home,
      rel: artefact.rel(),
      cfg,
      ctx,
    }),
    _ => template(home, artefact.rel()),
  }
}

struct Template<'a> {
  home: &'a Path,
  rel: &'a str,
  cfg: &'a Config,
  ctx: &'a RenderContext<'a>,
}

/// Seed `rel` at `dest` only when `dest` is absent.
///
/// **USER-OWNED FILES ARE SEEDED, NEVER SYNCED.** `usage-rules.md` is a
/// project's terse rule contract and `.intent_critic.yml` is its gate
/// configuration; overwriting either to cure variation destroys the thing the
/// project actually decided. v2's canon installer draws the same line.
fn seed_if_absent(
  template: Template<'_>,
  dest: &Path,
  force: bool,
  report: bool,
  applied: &mut Applied,
) -> Result<(), CanonError> {
  // Every seed goes through the one token expander, so a template that gains a
  // `[[TOKEN]]` renders it rather than shipping it literally (issue 0336: the
  // seeded `usage-rules.md` carried `[[PROJECT_NAME]]`). Only a Markdown seed
  // also gets the empty-section placeholder, which reads a `#` line as a heading:
  // in `.intent_critic.yml` that line is a comment, and the placeholder written
  // after it made the seed invalid YAML (issue 0564). So a template in any other
  // format, and a Markdown one with no token and no empty section, is written as
  // its bytes stand.
  let body = seed_body(&template)?;
  // **`preserved` NAMES A FILE THAT DIFFERS FROM WHAT CANON WOULD SEED** (issue
  // 0565). An existing file was reported as "yours, not canon's" without being
  // read, so a seed byte-identical to its template was called the project's
  // own. It is compared with the rendered seed first, and one that matches is
  // `unchanged`, as a generated file that matches is.
  if dest.exists() && !force {
    match std::fs::read_to_string(dest) {
      Ok(current) if current == body => applied.unchanged.push(dest.to_path_buf()),
      _ => applied.preserved.push(dest.to_path_buf()),
    }
    return Ok(());
  }
  write_if_changed(dest, &body, report, applied)
}

/// What canon would seed for `template`, rendered for this project.
///
/// **ONE RENDERING FOR EVERY QUESTION ABOUT A SEED.** [`seed_if_absent`] writes
/// it and compares an existing file with it (issue 0565), and [`relayout`]
/// removes a `usage-rules.md` only when it is byte-identical to it, so both
/// must mean the same bytes. Every seed goes through the one token expander,
/// so a template that gains a `[[TOKEN]]` renders it rather than shipping it
/// literally (issue 0336). Only a Markdown seed also gets the empty-section
/// placeholder, which reads a `#` line as a heading: in `.intent_critic.yml`
/// that line is a comment, and the placeholder written after it made the seed
/// invalid YAML (issue 0564).
fn seed_body(template: &Template<'_>) -> Result<String, CanonError> {
  let text = self::template(template.home, template.rel)?;
  if template.rel.ends_with(".md") {
    crate::rootfiles::substitute(&text, template.cfg, template.ctx)
  } else {
    crate::rootfiles::expand(&text, template.cfg, template.ctx)
  }
  .map_err(|e| CanonError::RootFile(format!("{}: {e:?}", template.rel)))
}

/// What [`relayout`] did, every path relative to the project root.
#[derive(Debug, Default)]
pub struct Relayout {
  /// Each contract moved, from where it was to where it is.
  pub moved: Vec<(PathBuf, PathBuf)>,
  /// A `usage-rules.md` byte-identical to its seed, removed on the way to
  /// `dotclaude`, which seeds none (hv's ruling 9 on ST0083).
  pub removed: Vec<PathBuf>,
  /// A `usage-rules.md` somebody wrote, left where it is and named.
  pub left: Vec<PathBuf>,
}

/// Move the two agent contracts from where `cfg` places them to where `target`
/// does, then write the `contracts` key (ST0083, `intent agents layout`).
///
/// **EVERY REFUSAL IS DECIDED BEFORE ANYTHING MOVES.** A destination holding a
/// file with other bytes is refused by name, and nothing is touched; one with
/// the same bytes needs no move, so the source is removed. A tracked contract
/// moves through git: the move is made on disk and both paths are staged, which
/// git records as the rename. **THE KEY IS WRITTEN LAST**, so a failure on the
/// way leaves the old key, and a re-run finds what already moved and finishes.
pub fn relayout(
  root: &Path,
  home: &Path,
  cfg: &Config,
  ctx: &RenderContext<'_>,
  target: Contracts,
) -> Result<Relayout, CanonError> {
  let read = |path: &Path| {
    std::fs::read(path).map_err(|source| CanonError::LayoutIo {
      path: path.to_path_buf(),
      source,
    })
  };
  let mut done = Relayout::default();
  let mut plan: Vec<(PathBuf, PathBuf)> = Vec::new();
  for name in ["AGENTS.md", "CLAUDE.md"] {
    let from = crate::sync::root_file_path(name, cfg.contracts);
    let to = crate::sync::root_file_path(name, target);
    if from == to || !root.join(&from).is_file() {
      continue;
    }
    if root.join(&to).exists() && read(&root.join(&to))? != read(&root.join(&from))? {
      return Err(CanonError::LayoutDestinationHolds { path: to });
    }
    plan.push((from, to));
  }
  let usage_rules = PathBuf::from("usage-rules.md");
  let mut remove_usage_rules = false;
  if target == Contracts::Dotclaude && root.join(&usage_rules).is_file() {
    let seed = seed_body(&Template {
      home,
      rel: Artefact::UsageRules.rel(),
      cfg,
      ctx,
    })?;
    if read(&root.join(&usage_rules))? == seed.as_bytes() {
      remove_usage_rules = true;
    } else {
      done.left.push(usage_rules.clone());
    }
  }

  let mut staged: Vec<String> = Vec::new();
  let tracked =
    |rel: &Path| crate::gitstate::is_tracked(root, &rel.to_string_lossy()).map_err(CanonError::Git);
  let unwritable = |path: &Path| {
    let path = path.to_path_buf();
    move |source| CanonError::LayoutIo { path, source }
  };
  for (from, to) in plan {
    let was_tracked = tracked(&from)?;
    let (source, dest) = (root.join(&from), root.join(&to));
    if let Some(parent) = dest.parent() {
      std::fs::create_dir_all(parent).map_err(unwritable(parent))?;
    }
    if dest.exists() {
      std::fs::remove_file(&source).map_err(unwritable(&source))?;
    } else {
      std::fs::rename(&source, &dest).map_err(unwritable(&dest))?;
    }
    if was_tracked {
      staged.push(from.to_string_lossy().into_owned());
      staged.push(to.to_string_lossy().into_owned());
    }
    done.moved.push((from, to));
  }
  if remove_usage_rules {
    let was_tracked = tracked(&usage_rules)?;
    let path = root.join(&usage_rules);
    std::fs::remove_file(&path).map_err(unwritable(&path))?;
    if was_tracked {
      staged.push(usage_rules.to_string_lossy().into_owned());
    }
    done.removed.push(usage_rules);
  }
  crate::gitstate::stage(root, &staged).map_err(CanonError::Git)?;

  let mut config = cfg.clone();
  config.contracts = target;
  crate::project::write_config(root, &config).map_err(CanonError::Config)?;
  Ok(done)
}

/// The repository's hooks directory, or `None` when there is no repository.
///
/// **`None` MEANS THE QUESTION COULD NOT BE ASKED, NEVER "THERE ARE NO HOOKS".**
/// Same rule as [`crate::sync`]'s git helpers: a project outside a repository
/// has no chain block to install and that is a fact about the project, not a
/// failure -- but it must reach the caller as an absence it can report rather
/// than as a silently skipped step.
///
/// `--git-path` is asked rather than `.git/hooks` assumed, because `core.hooksPath`
/// relocates the directory and a worktree's `.git` is a file. Both are ordinary
/// in this estate: Intent's own hooks live at `.githooks/` behind exactly that
/// setting, so a hard-coded `.git/hooks` would canonise the one path nothing runs.
pub fn hooks_dir(root: &Path) -> Option<PathBuf> {
  let out = std::process::Command::new("git")
    .args(["rev-parse", "--git-path", "hooks"])
    .current_dir(root)
    .output()
    .ok()?;
  if !out.status.success() {
    return None;
  }
  let rel = String::from_utf8_lossy(&out.stdout).trim().to_string();
  if rel.is_empty() {
    return None;
  }
  let path = PathBuf::from(&rel);
  Some(if path.is_absolute() {
    path
  } else {
    root.join(path)
  })
}

/// Apply v3 canon to the project rooted at `root`.
///
/// `git_hooks` is the resolved hooks directory (`git rev-parse --git-path
/// hooks`), passed in rather than resolved here so this module runs the same
/// way against a fixture as against a real clone -- and so a project with no
/// git is a `None` the caller decides about rather than a failure invented in
/// the middle of a write.
///
/// [`Options::skip_settings`] leaves `.claude/settings.json` alone and reports it as
/// [`Applied::skipped`] -- v2's `--skip-settings`, the one way for a project to
/// take Intent's canon without Claude Code lifecycle hooks (issue `0143`). It
/// declines the settings file only: v3 writes no per-project hook scripts, so
/// the other half of v2's escape hatch has nothing to skip.
pub fn apply(
  root: &Path,
  home: &Path,
  cfg: &Config,
  ctx: &RenderContext<'_>,
  git_hooks: Option<&Path>,
  opts: Options,
  skills: Option<&crate::payload::Payload>,
) -> Result<Applied, CanonError> {
  let mut applied = Applied::default();

  // 1. The hook door. Written from the template rather than composed here: the
  //    three hook names and their timeouts are canon, and a second spelling of
  //    them in Rust is the two-homes defect in the file whose whole job is to
  //    make every project agree.
  //
  //    **AND IT IS HELD WHEN IT IS NOT OURS, WHICH IT WAS NOT UNTIL v3.0.2.**
  //    This wrote the template over whatever was there, in the same function
  //    that holds `CLAUDE.md` twenty lines below on exactly this reasoning. A
  //    project with its own Claude Code settings -- permissions, a model pin,
  //    hooks of its own -- lost the file to a verb it ran to update its
  //    documentation, at rc=0, with the file listed as written.
  let settings_path = root.join(".claude/settings.json");
  // Read once, and only when the answer can matter: `--force` and
  // `--skip-settings` both decide without it.
  let settings_is_ours = opts.force
    || !settings_path.exists()
    || carries_hook_door(&std::fs::read_to_string(&settings_path).unwrap_or_default());
  // 0. The gate's releaser, BEFORE the settings that wire the gate, so a run
  //    never leaves the gate wired on a machine where nothing can release it
  //    when the install could have prevented it. Only where the settings file
  //    that will stand wires the gate: canon's template does, and a held file
  //    is the project's own, so it is asked rather than assumed.
  let wires_gate = if settings_is_ours {
    true
  } else {
    std::fs::read_to_string(&settings_path)
      .unwrap_or_default()
      .contains(GATE_HOOK)
  };
  if !opts.skip_settings
    && wires_gate
    && let Some(skills) = skills
  {
    applied.releaser = Some(install_releaser(skills, opts.report));
  }
  if opts.skip_settings {
    applied.skipped.push(settings_path);
  } else if !settings_is_ours {
    // HELD, not silently left: a run that skipped the file that arms every
    // lifecycle hook would otherwise look identical to one with nothing to do.
    applied.held.push(settings_path);
  } else {
    let settings = template(home, Artefact::Settings.rel())?;
    // **A FILE THAT CARRIES THE DOOR IS MERGED, NOT REPLACED** (issue 0606):
    // Intent's entries are brought to the template's and every key the owner
    // added beside them is kept. Absent, or under `--force`, the template is
    // written whole as before. A file that does not parse is held.
    let current = if opts.force {
      None
    } else {
      std::fs::read_to_string(&settings_path).ok()
    };
    match current {
      None => write_if_changed(&settings_path, &settings, opts.report, &mut applied)?,
      Some(current) => match settings_merged(&current, &settings) {
        Some(body) => write_if_changed(&settings_path, &body, opts.report, &mut applied)?,
        None => applied.unparseable.push(settings_path),
      },
    }
  }

  // 1b. `.mcp.json`, which declares `intent mcp` to Claude Code (AC-24.1).
  //
  //    **SEEDED WHEN ABSENT AND NEVER OVERWRITTEN, THROUGH THE SAME DOOR
  //    `usage-rules.md` USES.** A project that has hand-edited it -- a second
  //    server, an env var, a different command -- keeps it, and `--force` does
  //    NOT reach it: that flag's own help names `CLAUDE.md` without the
  //    marker, `.claude/settings.json` without Intent's hook door, and
  //    `.intent_critic.yml`, and stops there.
  //
  //    **IT CARRIES NO TOOL LIST, DELIBERATELY.** What is exposed on MCP is the
  //    register's `exposed_on_mcp` rows; a list here would be a second place
  //    that decides it, and the register would stop being the answer.
  let mcp_path = root.join(".mcp.json");
  if opts.skip_settings {
    applied.skipped.push(mcp_path);
  } else {
    seed_if_absent(
      Template {
        home,
        rel: Artefact::Mcp.rel(),
        cfg,
        ctx,
      },
      &mcp_path,
      false,
      opts.report,
      &mut applied,
    )?;
  }

  // 2. Generated root files. DELEGATED -- `rootfiles` owns substitution and the
  //    language-conditional blocks, and a second renderer here would drift from
  //    it the first time a template grew a new block form.
  for name in ["CLAUDE.md", "AGENTS.md"] {
    // Where the `contracts` key places them (ST0083): the root or `.claude/`,
    // and never a root copy under `dotclaude`.
    let dest = root.join(crate::sync::root_file_path(name, cfg.contracts));
    // **`CLAUDE.md` IS REGENERATED ONLY WITH ITS OWN CONSENT.** A copy carrying
    // no generated footer was authored by a person, and overwriting it to cure
    // variation destroys what the project actually decided -- the cure worse
    // than the disease. `AGENTS.md` is exempt because it is generated BY
    // DEFINITION: `in-essentials` rule 2 forbids editing it by hand, and `init`
    // generates it from project state rather than seeding a template copy
    // (`init.rs`, `Generated("AGENTS.md")`).
    if name == "CLAUDE.md" && dest.exists() && !opts.force {
      let current = std::fs::read_to_string(&dest).unwrap_or_default();
      if !is_generated_contract(name, &current) {
        applied.held.push(dest);
        continue;
      }
    }
    let mut content = crate::rootfiles::render(home, name, cfg, ctx)
      .map_err(|e| CanonError::RootFile(format!("{name}: {e:?}")))?;
    // The project's own directives are carried across, never regenerated. See
    // `carry_user_block` -- the template promises this in its own text.
    if name == "CLAUDE.md" && dest.exists() {
      let current = std::fs::read_to_string(&dest).unwrap_or_default();
      content = carry_user_block(&current, &content);
    }
    write_if_changed(&dest, &content, opts.report, &mut applied)?;
  }

  // 3. User-owned. Seeded when absent, preserved otherwise.
  //
  // **UNDER `dotclaude` AN ABSENT `usage-rules.md` IS NOT SEEDED** (hv's ruling
  // 9 on ST0083): the layout exists so a tree's root carries no tooling file
  // for the people who open it, and a seed there has no reader. One somebody
  // wrote stays at the root and is reported as preserved, as in `root`.
  let usage_rules = root.join("usage-rules.md");
  if cfg.contracts == Contracts::Root || usage_rules.exists() {
    seed_if_absent(
      Template {
        home,
        rel: Artefact::UsageRules.rel(),
        cfg,
        ctx,
      },
      &usage_rules,
      // NOT force-overwritable. `--force`'s own help names `CLAUDE.md`,
      // `.claude/settings.json` and `.intent_critic.yml` and stops there, and v2
      // writes this one only when absent. Widening a documented flag past its own
      // text is how a destructive option grows in the dark.
      false,
      opts.report,
      &mut applied,
    )?;
  }
  seed_if_absent(
    Template {
      home,
      rel: Artefact::CriticConfig.rel(),
      cfg,
      ctx,
    },
    &root.join(".intent_critic.yml"),
    opts.force,
    opts.report,
    &mut applied,
  )?;

  // 4. The gate, in two halves: THE CARRIER FIRST, THEN THE BLOCK THAT SOURCES
  //    IT. See [`install_carrier`] for why the order is the whole point.
  if let Some(hooks) = git_hooks {
    install_carrier(home, hooks, opts.report, &mut applied)?;

    // The chain block. See the module header: region-edited, never regenerated.
    chain_hook(
      &hooks.join("pre-commit"),
      "pre-commit",
      opts.report,
      &mut applied,
    )?;

    // 5. The store after a pull (ST0078 WP-03): the same two halves, carrier
    //    first, for each hook that follows a change git makes to the tree.
    for name in POST_PULL_HOOKS {
      install_post_pull_carrier(home, hooks, name, opts.report, &mut applied)?;
      chain_hook(&hooks.join(name), name, opts.report, &mut applied)?;
    }
  }

  Ok(applied)
}

/// Bring one hook's chain block to canon's, and the hook to executable: the
/// one path for the gate and every post-pull hook alike.
///
/// **A HOOK WHOSE BLOCK CANNOT BE REWRITTEN IS HELD, WITH ITS REASON, AND IS
/// NEVER REPORTED `unchanged`** (issue `0538`). [`insert_chain_block`] answers
/// `None` both for canon's block and for one it must leave alone, and only the
/// first is canonical. The second keeps whatever block it had, so it is the one
/// case that can still pass a commit in silence, and it is named.
fn chain_hook(
  hook: &Path,
  name: &str,
  report: bool,
  applied: &mut Applied,
) -> Result<(), CanonError> {
  let existing = std::fs::read_to_string(hook).unwrap_or_default();
  match insert_chain_block(name, &existing) {
    Some(updated) => write_if_changed(hook, &updated, report, applied)?,
    None => match chain_block_held(&existing) {
      Some(why) => applied.blocks_held.push((hook.to_path_buf(), why)),
      None => applied.unchanged.push(hook.to_path_buf()),
    },
  }
  // **OUTSIDE THE MATCH, SO IT RUNS ON THE ALREADY-BLOCKED PATH TOO.** It
  // used to sit in the `Some` arm only, which left the one state nothing
  // would ever repair: a hook carrying a correct chain block that git will
  // not execute. That is the same silent skip the carrier half closes,
  // one file up -- and `insert_chain_block` returning `None` is exactly the
  // "already correct" report that made it invisible.
  if !report {
    make_executable(hook)?;
  }
  Ok(())
}

/// Install `hooks/post-pull.sh` as `<hooks>/<hook>.intent`, the carrier the
/// hook's chain block calls (ST0078 WP-03).
///
/// **A COPY OF ONE TEMPLATE UNDER THREE NAMES**, read from the resolved install
/// root like [`install_carrier`]'s shim; the carrier reads its own name to
/// know which hook ran it. Executable on the unchanged path too, for
/// [`install_carrier`]'s reason: `[ -x ]` is what the chain block tests.
fn install_post_pull_carrier(
  home: &Path,
  hooks: &Path,
  hook: &str,
  report: bool,
  applied: &mut Applied,
) -> Result<(), CanonError> {
  let carrier = hooks.join(carrier_name(hook));
  let body = template(home, Artefact::PostPullCarrier.rel())?;
  write_if_changed(&carrier, &body, report, applied)?;
  if report {
    return Ok(());
  }
  make_executable(&carrier)
}

/// Install the pre-commit shim as `<hooks>/pre-commit.intent` -- the carrier.
///
/// **THE ORDER MATTERS AND ITS ABSENCE WAS THE DEFECT.** The chain block this
/// module wrote was `if [ -x "$_intent_chain" ]; then ... fi` with no `else`,
/// so a project whose carrier was never installed passed every commit at rc=0
/// while every report anyone read said the gate was wired. [`chain_block`] now
/// refuses such a commit ("GATE ABSENT"), and this function is the repair
/// that refusal names (issue 0570 drove both). Until this function
/// existed, [`apply`] wrote that block **and nothing in either tree wrote the
/// carrier** -- so the one verb whose job is wiring the gate produced, by
/// itself, a project running zero guards and saying nothing. Baize is the
/// measured instance: config `3.0.0`, canon present, fully ported, no gate.
///
/// The shim's own contract is *refusing, not skipping* (hv ruling 4). That
/// contract is unreachable from one layer up: a shim that was never installed
/// is not a shim that refuses, it is a `[ -x ]` that is false.
///
/// **THE BYTES COME FROM THE RESOLVED INSTALL ROOT'S OWN TEMPLATE**, through
/// the same [`template`] reader every other canon artefact uses. dc measured
/// eleven estates carrying the FROZEN v2 tree's gate byte for byte, ten of them
/// stamped the same day -- the last fleet-wide install seeded them from a tree
/// nobody develops in. **The defect was what the installer READ, not whether it
/// ran**, so an installer reading from anywhere but the root the running binary
/// resolved would reproduce precisely today's state, correctly and at rc=0.
///
/// **THE MODE IS SET ON THE UNCHANGED PATH TOO.** `[ -x ]` is the test the
/// chain block applies, so correct bytes with the wrong mode are the silent
/// skip with every byte in place -- and it is the one state a
/// `write_if_changed` short-circuit would leave untouched on every future run.
fn install_carrier(
  home: &Path,
  hooks: &Path,
  report: bool,
  applied: &mut Applied,
) -> Result<(), CanonError> {
  let carrier = hooks.join(carrier_name("pre-commit"));
  let shim = template(home, Artefact::PreCommitCarrier.rel())?;
  write_if_changed(&carrier, &shim, report, applied)?;
  // **ASKED AT INSTALL TIME BECAUSE THE ALTERNATIVE IS ASKING AT COMMIT TIME.**
  // The carrier is a shim: it does nothing except resolve this pointer and exec
  // what it names. So `written` is a claim about bytes and says nothing about
  // whether the gate can run -- and the operator is looking HERE, not at their
  // next commit. Recorded rather than refused: a project must still be able to
  // become canonical from a machine whose pointer is temporarily wrong, and
  // refusing to install would leave it with no gate at all, which is the state
  // this whole change exists to end.
  applied.gate = Some(crate::install::gate_resolution(Some(home)));
  if report {
    return Ok(());
  }
  make_executable(&carrier)
}

/// A pre-commit hook git will not execute is a guard that silently never runs.
fn make_executable(path: &Path) -> Result<(), CanonError> {
  #[cfg(unix)]
  {
    use std::os::unix::fs::PermissionsExt;
    let mut perms = std::fs::metadata(path)
      .map_err(|source| CanonError::Unreadable {
        path: path.to_path_buf(),
        source,
      })?
      .permissions();
    perms.set_mode(perms.mode() | 0o111);
    std::fs::set_permissions(path, perms).map_err(|source| CanonError::Unwritable {
      path: path.to_path_buf(),
      source,
    })?;
  }
  Ok(())
}

/// Put the prompt gate's releaser on this machine when it is absent (issue
/// `0601`, (a1)): `in-session` through the same installer `intent claude skills
/// install` uses, so the manifest records it and `skills sync` and `uninstall`
/// treat it as any other skill.
///
/// **NEVER FORCED.** An installed `in-session` without the releaser is held, not
/// overwritten: whatever is there is the operator's, and `skills sync` is the
/// door that reports a local change before taking the source copy.
fn install_releaser(skills: &crate::payload::Payload, report: bool) -> Releaser {
  let dir = skills.installed_dir(GATE_SKILL);
  let releaser = dir.join(GATE_RELEASER);
  if releaser.is_file() {
    return Releaser::Present { dir };
  }
  if skills.is_installed(GATE_SKILL) {
    return Releaser::Held { dir };
  }
  if report {
    return Releaser::Installed { dir };
  }
  match skills.install(&[GATE_SKILL.to_string()], false) {
    Err(e) => Releaser::Failed {
      cause: e.to_string(),
    },
    Ok(_) if releaser.is_file() => Releaser::Installed { dir },
    Ok(report) => Releaser::Failed {
      cause: match report.steps.first().map(|step| &step.outcome) {
        Some(crate::payload::Outcome::SourceMissing) => {
          format!("the running Intent's canon carries no `{GATE_SKILL}` skill to install")
        }
        _ => format!("the install left no `{GATE_RELEASER}` in {}", dir.display()),
      },
    },
  }
}
